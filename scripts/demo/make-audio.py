WITHIN_TURN_GAP = 0.8   # ثانية بين جمل المتحدث الواحد
BETWEEN_TURNS_GAP = 1.8  # ثانية بين تبدّل المتحدثين
ROUNDS = 2               # تُعاد المقابلة بصياغة «الجزء الثاني» لتتجاوز عشر دقائق


def speak(text: str, path: str, voice: str, speed: int) -> float:
    subprocess.run(
        ["espeak-ng", "-v", voice, "-s", str(speed), "-w", path, text],
        check=True,
        capture_output=True,
    )
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
        check=True,
        capture_output=True,
        text=True,
    )
    return float(out.stdout.strip())


def silence(path: str, seconds: float) -> None:
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i",
         f"anullsrc=r=22050:cl=mono", "-t", f"{seconds:.3f}", path],
        check=True,
    )


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    tmp = tempfile.mkdtemp(prefix="demo-audio-")
    parts: list[str] = []
    words: list[dict] = []
    cursor = 0.0
    n = 0

    turns = []
    for r in range(ROUNDS):
        for speaker, sentences in TURNS:
            if r == 1 and speaker == "المحاور" and sentences is TURNS[0][1]:
                sentences = ["نكمل معكم الجزء الثاني من اللقاء.", "ونعيد لكم أبرز ما قاله ضيفنا."]
            turns.append((speaker, sentences))

    for t_index, (speaker, sentences) in enumerate(turns):
        # صوتان مختلفان للمتحدثَين، كما في تسجيل حقيقي
        voice, speed = ("ar", 135) if speaker == "المحاور" else ("ar+m3", 125)
        for s_index, sentence in enumerate(sentences):
            wav = os.path.join(tmp, f"s{n:04d}.wav")
            duration = speak(sentence, wav, voice, speed)
            parts.append(wav)

            tokens = sentence.split()
            total_chars = sum(len(t) for t in tokens)
            t = cursor
            for token in tokens:
                share = duration * len(token) / total_chars
                words.append({
                    "text": token,
                    "startMs": round(t * 1000),
                    "endMs": round((t + share) * 1000),
                    "speaker": speaker,
                    "turn": t_index,
                })
                t += share
            cursor += duration
            n += 1

            last_in_turn = s_index == len(sentences) - 1
            gap = BETWEEN_TURNS_GAP if last_in_turn else WITHIN_TURN_GAP
            sil = os.path.join(tmp, f"g{n:04d}.wav")
            silence(sil, gap)
            parts.append(sil)
            cursor += gap

    listing = os.path.join(tmp, "list.txt")
    with open(listing, "w") as f:
        for p in parts:
            f.write(f"file '{p}'\n")

    mp3 = os.path.join(OUT_DIR, "interview.mp3")
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0",
         "-i", listing, "-ar", "22050", "-ac", "1", "-b:a", "64k", mp3],
        check=True,
    )

    with open(os.path.join(OUT_DIR, "script.json"), "w", encoding="utf-8") as f:
        json.dump({"durationMs": round(cursor * 1000), "words": words}, f, ensure_ascii=False)

    print(f"{mp3}: {cursor/60:.1f} دقيقة، {len(words)} كلمة، {n} جملة")


if __name__ == "__main__":
    main()
