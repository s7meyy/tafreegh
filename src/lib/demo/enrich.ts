const LIGHT = new Set(["من", "في", "على", "الله", "القصيم", "وش"]);

export function demoDiacritize(paragraphs: readonly string[], mode: TashkeelMode): string[] {
  return paragraphs.map((p) =>
    p.replace(/[ء-ي]+/g, (word) => {
      if (mode === "light" && !LIGHT.has(word)) return word;
      return FULL[word] ?? word;
    }),
  );
}

export function demoSummarize(paragraphs: readonly string[]): SummaryData {
  const find = (...keys: string[]) =>
    paragraphs
      .map((p, i) => (keys.some((k) => p.includes(k)) ? i + 1 : 0))
      .filter(Boolean)
      .slice(0, 3);

  if (!paragraphs.some((p) => p.includes("النخل"))) {
    return {
      brief: paragraphs[0]?.split(/[.؟!]/)[0] ?? "",
      points: paragraphs.slice(0, 3).map((p, i) => ({ text: p.split(/[.؟!]/)[0]!, paras: [i + 1] })),
      topics: [],
    };
  }

  return {
    brief:
      "حوار مع مزارع نخل من بريدة يعمل في الزراعة منذ أكثر من عشرين سنة، يتحدث فيه عن أصناف التمور ونشأة مزرعته، وتحوّل الري من السواني إلى التنقيط، وآفة سوسة النخيل، والتسويق والصرام وعمالة المزرعة.",
    points: [
      { text: "الضيف عبدالله بن سعود مزارع من بريدة، ويصف موسم هذه السنة بأنه جيد.", paras: find("عبدالله بن سعود") },
      { text: "السكري أشهر أصناف القصيم، ومعه الخلاص والصقعي والبرحي، ويُطلب من الكويت والإمارات.", paras: find("السكري وهو الأشهر") },
      { text: "انتقل الري من السواني قديمًا إلى التنقيط الذي يوفّر أكثر من نصف الماء.", paras: find("السواني", "التنقيط") },
      { text: "سوسة النخيل الحمراء أكبر تحدٍّ، وتُكافح بفحص النخل كل أسبوعين تقريبًا.", paras: find("سوسة") },
      { text: "السعر يعتمد على الجودة والحجم، وللتسويق الإلكتروني ومهرجان التمور في بريدة دور متزايد.", paras: find("مهرجان", "إلكتروني") },
      { text: "الصرام هو قطف التمر آخر الصيف، وتزيد فيه العمالة.", paras: find("الصرام هو") },
      // إسناد إلى فقرة غير موجودة — يُسقطه التنظيف
      { text: "يدعو الضيف إلى دعم المنتج المحلي.", paras: [...find("ادعموا"), 9999] },
    ],
    topics: ["زراعة النخيل", "أصناف التمور", "الري", "سوسة النخيل", "التسويق"],
  };
}
